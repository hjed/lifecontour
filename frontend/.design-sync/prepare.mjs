// Generates the two inputs the converter needs but this repo doesn't otherwise
// produce. This is `cfg.buildCmd` — run it from frontend/ before
// package-build.mjs, and again after authoring preview cards.
//
//   1. .design-sync/.cache/compiled.css  (cfg.cssEntry)
//      src/app/globals.css is a Tailwind v4 *source* file, not a stylesheet.
//      Shipping it as-is would send `@import 'tailwindcss'` to the browser and
//      every component would render unstyled. Tailwind only generates the
//      utilities it can see, so preview cards must be scanned too — hence the
//      @source roots in preview.css and the "run it again after authoring" rule.
//
//   2. types/**/*.d.ts
//      The app is `noEmit`, so there is no declaration tree for the converter's
//      prop extractor and every <Name>Props came out as `[key: string]: unknown`
//      — leaving the design agent with no API contract at all. A
//      declaration-only tsc pass fixes that. findTypesRoot() discovers `types/`
//      by convention, so package.json needs no `types` field.

import { execFileSync } from 'node:child_process';
import {
  mkdirSync,
  statSync,
  existsSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';

const TW_CLI = '.ds-sync/node_modules/@tailwindcss/cli/dist/index.mjs';
const CSS_IN = '.design-sync/preview.css';
const CSS_OUT = '.design-sync/.cache/compiled.css';
const TS_PROJECT = '.design-sync/tsconfig.types.json';

mkdirSync('.design-sync/.cache', { recursive: true });
mkdirSync('.design-sync/previews', { recursive: true });

// ── 1. stylesheet
execFileSync(process.execPath, [TW_CLI, '-i', CSS_IN, '-o', CSS_OUT], {
  stdio: 'inherit',
});
console.error(`  css: ${CSS_OUT} (${statSync(CSS_OUT).size} bytes)`);

// ── 2. declarations
execFileSync('./node_modules/.bin/tsc', ['-p', TS_PROJECT], {
  stdio: 'inherit',
});
if (!existsSync('types')) {
  throw new Error(
    'tsc emitted no types/ directory — prop extraction will be empty'
  );
}
console.error('  types: types/ declaration tree emitted');

// ── 3. index.d.ts — the types entry the prop extractor falls back to.
//
// The declaration tree alone is not enough. `propsBodyFor` first looks for a
// named `<Name>Props` interface, which tsc does NOT emit here (the props type is
// local to each component file, so it gets inlined into the
// ForwardRefExoticComponent signature). It then falls back to the component
// symbol exported from `<pkg>/index.d.ts` — which did not exist, so every
// component emitted `[key: string]: unknown` and the design agent got no API
// contract at all.
//
// This file provides that entry. It re-exports EXACTLY the components in
// componentSrcMap and no more: `exportedNames()` reads this file to build the
// component list, so re-exporting the whole tree would balloon the synced set
// from the intended 47 primaries to all 158 exports.
const cfg = JSON.parse(readFileSync('.design-sync/config.json', 'utf8'));
const byModule = new Map();
for (const [name, src] of Object.entries(cfg.componentSrcMap)) {
  if (src === null) continue; // preview-only helpers are not components
  const mod = './' + src.replace(/^src\//, 'types/').replace(/\.tsx?$/, '');
  if (!byModule.has(mod)) byModule.set(mod, []);
  byModule.get(mod).push(name);
}
const lines = [
  '// GENERATED by .design-sync/prepare.mjs — do not edit, do not commit.',
  '// Types entry for the design-sync prop extractor. See prepare.mjs step 3.',
  '',
];
for (const [mod, names] of [...byModule].sort()) {
  lines.push(`export { ${names.sort().join(', ')} } from '${mod}';`);
}
writeFileSync('index.d.ts', lines.join('\n') + '\n');
console.error(
  `  types: index.d.ts re-exports ${[...byModule.values()].flat().length} components from ${byModule.size} modules`
);
