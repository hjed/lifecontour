/**
 * ActivityItem component displays a single activity/history entry in the feed.
 *
 * Shows field changes with timestamp, action description, and visual indicators.
 */

'use client';

import { formatDistanceToNow } from 'date-fns';
import { enAU } from 'date-fns/locale';
import {
  Edit,
  PlusCircle,
  Trash2,
  Monitor,
  Terminal,
  Cloud,
  Activity,
  Sparkles,
  Settings,
  ChevronDown,
  ChevronRight,
} from 'lucide-react';
import { useState } from 'react';
import type { ContactHistoryResource } from '@/types/contacts';
import { cn } from '@/lib/utils';
import {
  Tooltip,
  TooltipContent,
  TooltipTrigger,
} from '@/components/ui/tooltip';
import { Button } from '@/components/ui/button';

interface ActivityItemProps {
  readonly activity: ContactHistoryResource;
  readonly className?: string;
}

/**
 * Format a field name for display (e.g., "first_name" -> "First Name").
 * Handles edge cases like empty strings and ensures proper capitalization.
 */
function formatFieldName(fieldName: string): string {
  if (!fieldName) return '';
  return fieldName
    .split('_')
    .filter(word => word.length > 0)
    .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(' ');
}

/**
 * Get activity type based on old and new values.
 */
function getActivityType(
  oldValue: string | null,
  newValue: string | null
): 'created' | 'updated' | 'deleted' {
  if (!oldValue && newValue) return 'created';
  if (oldValue && !newValue) return 'deleted';
  return 'updated';
}

/**
 * Get icon for activity type.
 */
function getActivityIcon(type: 'created' | 'updated' | 'deleted') {
  switch (type) {
    case 'created':
      return <PlusCircle className='h-4 w-4 text-green-500' />;
    case 'deleted':
      return <Trash2 className='h-4 w-4 text-red-500' />;
    case 'updated':
    default:
      return <Edit className='h-4 w-4 text-blue-500' />;
  }
}

/**
 * Format the activity description based on field and values.
 */
function formatActivityDescription(
  fieldName: string,
  oldValue: string | null,
  newValue: string | null,
  entityType: string
): string {
  const formattedField = formatFieldName(fieldName);
  const activityType = getActivityType(oldValue, newValue);

  // Format entity type for display
  const entityLabel = entityType.replace(/_/g, ' ').replace('contact ', '');

  switch (activityType) {
    case 'created':
      return `Added ${formattedField}: "${newValue}"`;
    case 'deleted':
      return `Removed ${formattedField}`;
    case 'updated':
      return `Changed ${formattedField} from "${oldValue}" to "${newValue}"`;
    default:
      return `Modified ${entityLabel}`;
  }
}

/**
 * Format timestamp for display.
 */
function formatTimestamp(timestamp: string | null): string {
  if (!timestamp) return 'Unknown time';

  try {
    const date = new Date(timestamp);
    return formatDistanceToNow(date, {
      addSuffix: true,
      locale: enAU,
    });
  } catch {
    return 'Unknown time';
  }
}

function getProvenanceIcon(source: string) {
  switch (source) {
    case 'ui':
      return <Monitor className='text-muted-foreground h-3 w-3' />;
    case 'mcp':
      return <Terminal className='text-muted-foreground h-3 w-3' />;
    case 'google_contacts':
      return <Cloud className='text-muted-foreground h-3 w-3' />;
    case 'strava':
      return <Activity className='text-muted-foreground h-3 w-3' />;
    case 'summary_regeneration':
      return <Sparkles className='text-muted-foreground h-3 w-3' />;
    case 'system':
    default:
      return <Settings className='text-muted-foreground h-3 w-3' />;
  }
}

function getProvenanceLabel(source: string) {
  switch (source) {
    case 'ui':
      return 'Updated via Web Interface';
    case 'mcp':
      return 'Updated via AI Assistant';
    case 'google_contacts':
      return 'Updated via Google Contacts Sync';
    case 'strava':
      return 'Updated via Strava Sync';
    case 'summary_regeneration':
      return 'Generated by AI Summary';
    case 'system':
    default:
      return 'Updated by System';
  }
}

export function ActivityItem({ activity, className }: ActivityItemProps) {
  const { entity_type, field_name, old_value, new_value, created_at, source } =
    activity.attributes;
  const activityType = getActivityType(old_value, new_value);
  const [isExpanded, setIsExpanded] = useState(false);

  const isSummaryRegen = source === 'summary_regeneration';

  if (isSummaryRegen) {
    return (
      <div
        className={cn('flex flex-col gap-1 py-2', className)}
        data-testid={`activity-item-${activity.id}`}
      >
        <div className='flex items-start gap-3'>
          <div className='mt-0.5 flex-shrink-0'>
            <Tooltip>
              <TooltipTrigger asChild>
                <button
                  type='button'
                  className='cursor-help focus:outline-none'
                  data-testid={`provenance-trigger-${source}`}
                >
                  {getProvenanceIcon(source)}
                </button>
              </TooltipTrigger>
              <TooltipContent>{getProvenanceLabel(source)}</TooltipContent>
            </Tooltip>
          </div>
          <div className='min-w-0 flex-1'>
            <div className='flex items-center justify-between'>
              <p className='text-sm font-medium'>
                {field_name === 'summary_text'
                  ? 'AI Summary Regenerated'
                  : `AI Summary ${formatFieldName(field_name)} Updated`}
              </p>
              <div className='flex items-center gap-2'>
                <p className='text-muted-foreground text-xs'>
                  {formatTimestamp(created_at)}
                </p>
                <Button
                  variant='ghost'
                  size='icon'
                  className='h-6 w-6'
                  onClick={() => setIsExpanded(!isExpanded)}
                  aria-label={
                    isExpanded ? 'Collapse summary text' : 'Expand summary text'
                  }
                  aria-expanded={isExpanded}
                  aria-controls={`summary-content-${activity.id}`}
                >
                  {isExpanded ? (
                    <ChevronDown className='h-4 w-4' />
                  ) : (
                    <ChevronRight className='h-4 w-4' />
                  )}
                </Button>
              </div>
            </div>
            {isExpanded && (
              <div
                id={`summary-content-${activity.id}`}
                className='bg-muted mt-2 rounded-md p-2 text-xs'
              >
                <p className='whitespace-pre-wrap'>
                  {new_value === '' ? 'Empty' : (new_value ?? 'None')}
                </p>
              </div>
            )}
          </div>
        </div>
      </div>
    );
  }

  return (
    <div
      className={cn('flex items-start gap-3 py-2', className)}
      data-testid={`activity-item-${activity.id}`}
    >
      {/* Action Icon */}
      <div className='mt-0.5 flex-shrink-0'>
        {getActivityIcon(activityType)}
      </div>

      {/* Content */}
      <div className='min-w-0 flex-1'>
        <p className='text-sm'>
          {formatActivityDescription(
            field_name,
            old_value,
            new_value,
            entity_type
          )}
        </p>
        <div className='mt-1 flex items-center gap-2'>
          <Tooltip>
            <TooltipTrigger asChild>
              <button
                type='button'
                className='flex cursor-help items-center focus:outline-none'
                data-testid={`provenance-trigger-${source || 'system'}`}
              >
                {getProvenanceIcon(source || 'system')}
              </button>
            </TooltipTrigger>
            <TooltipContent>
              {getProvenanceLabel(source || 'system')}
            </TooltipContent>
          </Tooltip>
          <p className='text-muted-foreground text-xs'>
            {formatTimestamp(created_at)}
          </p>
        </div>
      </div>
    </div>
  );
}

// Export utility functions for testing
export { formatFieldName, getActivityType, formatActivityDescription };
