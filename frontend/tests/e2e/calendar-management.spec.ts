import { test, expect } from './fixtures';

test.describe('Calendar Management', () => {
  test('can create, edit and delete a calendar', async ({
    authenticatedPage: page,
  }) => {
    // Each submit below is a single click followed by a web-first assertion that
    // the dialog closed, rather than a click wrapped in `toPass`. Retrying the
    // click is unsound here: the click always lands (the dialog was opened by a
    // click and its fields filled, so the page is fully interactive), and once
    // it has landed the button unmounts as the dialog closes. A retry loop with
    // a short inner budget therefore turns a slow round-trip into a permanent
    // failure — every later attempt waits out the action timeout on a button
    // that no longer exists. The only thing worth waiting on is the API call, so
    // let the global expect timeout cover it.
    //
    // Each dialog is addressed by its accessible name (Radix labels the content
    // from its DialogTitle) so every assertion names the dialog it means, and no
    // locator can widen to a different one.
    const createDialog = page.getByRole('dialog', { name: 'Create Calendar' });
    const editDialog = page.getByRole('dialog', { name: 'Edit Calendar' });
    const deleteDialog = page.getByRole('dialog', { name: 'Delete Calendar' });

    // 1. Navigate to Settings page
    await page.goto('/settings');
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible();

    // 2. Open Create Calendar dialog
    await page.getByRole('button', { name: 'Add Calendar' }).click();
    await expect(createDialog).toBeVisible();

    // 3. Fill in calendar details
    const calendarName = `E2E Calendar ${Date.now()}`;
    await createDialog.getByLabel(/name/i).fill(calendarName);
    await createDialog.getByLabel(/description/i).fill('Generated by E2E test');
    await createDialog.getByTestId('color-input').fill('#123456');

    // 4. Submit and wait for creation
    await createDialog.getByRole('button', { name: /save changes/i }).click();
    await expect(createDialog).toBeHidden();

    await expect(page.getByText(calendarName)).toBeVisible();

    // 5. Edit the calendar
    await page
      .getByRole('button', {
        name: `Edit calendar ${calendarName}`,
      })
      .click();
    await expect(editDialog).toBeVisible();

    // Wait for the dialog to populate with the existing values before editing.
    // The form is reset asynchronously when the dialog opens (react-hook-form
    // useEffect), and the dialog is already mounted so its inputs become
    // fillable immediately. Filling before the reset commits lets the reset
    // silently overwrite our input back to the original name — a race that
    // surfaces as Firefox flakiness. Asserting the populated value first makes
    // the test wait for the reset to land.
    const nameInput = editDialog.getByLabel(/name/i);
    await expect(nameInput).toHaveValue(calendarName);

    // Change the name
    const updatedName = `${calendarName} (Updated)`;
    await nameInput.fill(updatedName);

    // Submit and wait for update
    await editDialog.getByRole('button', { name: /save changes/i }).click();
    await expect(editDialog).toBeHidden();

    // Verify updated name appears
    await expect(page.getByText(updatedName)).toBeVisible();
    await expect(page.getByText(calendarName, { exact: true })).toBeHidden();

    // 6. Delete the calendar
    await page
      .getByRole('button', {
        name: `Delete calendar ${updatedName}`,
      })
      .click();

    await expect(deleteDialog).toBeVisible();

    await deleteDialog.getByRole('button', { name: 'Delete' }).click();
    await expect(deleteDialog).toBeHidden();

    // Verify it's gone
    await expect(page.getByText(updatedName)).toBeHidden();
  });
});
