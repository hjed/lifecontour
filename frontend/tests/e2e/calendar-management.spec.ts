import { test, expect } from './fixtures';

test.describe('Calendar Management', () => {
  test('can create, edit and delete a calendar', async ({
    authenticatedPage: page,
  }) => {
    // 1. Navigate to Settings page
    await page.goto('/settings');
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible();

    // 2. Open Create Calendar dialog
    await page.getByRole('button', { name: 'Add Calendar' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();

    // 3. Fill in calendar details
    const calendarName = `E2E Calendar ${Date.now()}`;
    await page.getByLabel(/name/i).fill(calendarName);
    await page.getByLabel(/description/i).fill('Generated by E2E test');
    await page.getByTestId('color-input').fill('#123456');

    // 4. Submit and wait for creation
    await expect(async () => {
      await page.getByRole('button', { name: /save changes/i }).click();
      await expect(page.getByRole('dialog')).toBeHidden({ timeout: 2000 });
    }).toPass();

    await expect(page.getByText(calendarName)).toBeVisible();

    // 5. Edit the calendar
    await page
      .getByRole('button', {
        name: `Edit calendar ${calendarName}`,
      })
      .click();

    // Wait for the dialog to populate with the existing values before editing.
    // The form is reset asynchronously when the dialog opens (react-hook-form
    // useEffect), and the dialog is already mounted so its inputs become
    // fillable immediately. Filling before the reset commits lets the reset
    // silently overwrite our input back to the original name — a race that
    // surfaces as Firefox flakiness. Asserting the populated value first makes
    // the test wait for the reset to land.
    const nameInput = page.getByLabel(/name/i);
    await expect(nameInput).toHaveValue(calendarName);

    // Change the name
    const updatedName = `${calendarName} (Updated)`;
    await nameInput.fill(updatedName);

    // Submit and wait for update
    await expect(async () => {
      await page.getByRole('button', { name: /save changes/i }).click();
      await expect(page.getByRole('dialog')).toBeHidden({ timeout: 2000 });
    }).toPass();

    // Verify updated name appears
    await expect(page.getByText(updatedName)).toBeVisible();
    await expect(page.getByText(calendarName, { exact: true })).toBeHidden();

    // 6. Delete the calendar
    await page
      .getByRole('button', {
        name: `Delete calendar ${updatedName}`,
      })
      .click();

    await expect(
      page.getByRole('heading', { name: 'Delete Calendar' })
    ).toBeVisible();

    await expect(async () => {
      await page.getByRole('button', { name: 'Delete' }).click();
      await expect(page.getByRole('dialog')).toBeHidden({ timeout: 2000 });
    }).toPass();

    // Verify it's gone
    await expect(page.getByText(updatedName)).toBeHidden();
  });
});
