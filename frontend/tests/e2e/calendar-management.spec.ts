import { test, expect } from './fixtures';

test.describe('Calendar Management', () => {
  test('can create, edit and delete a calendar', async ({
    authenticatedPage: page,
  }) => {
    // 1. Navigate to Settings page
    await page.goto('/settings');
    await expect(page.getByRole('heading', { name: 'Settings' })).toBeVisible();

    // 2. Open Create Calendar dialog
    await page.getByRole('button', { name: 'Add Calendar' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();

    // 3. Fill in calendar details
    const calendarName = `E2E Calendar ${Date.now()}`;
    await page.getByLabel(/name/i).fill(calendarName);
    await page.getByLabel(/description/i).fill('Generated by E2E test');
    await page.getByTestId('color-input').fill('#123456');

    // 4. Submit and wait for creation
    await Promise.all([
      page.waitForResponse(
        response =>
          response.url().includes('/api/calendars') &&
          response.request().method() === 'POST' &&
          response.ok()
      ),
      page.getByRole('button', { name: /save changes/i }).click(),
    ]);

    // Verify dialog closed and calendar appears in the list
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await expect(page.getByText(calendarName)).toBeVisible();

    // 5. Edit the calendar
    await page
      .getByRole('button', {
        name: new RegExp(`Edit calendar ${calendarName}`, 'i'),
      })
      .click();

    // Change the name
    const updatedName = `${calendarName} (Updated)`;
    await page.getByLabel(/name/i).fill(updatedName);

    // Submit and wait for update
    await Promise.all([
      page.waitForResponse(
        response =>
          response.url().includes('/api/calendars/') &&
          response.request().method() === 'PUT' &&
          response.ok()
      ),
      page.getByRole('button', { name: /save changes/i }).click(),
    ]);

    // Verify dialog closed and updated name appears
    await expect(page.getByRole('dialog')).not.toBeVisible();
    await expect(page.getByText(updatedName)).toBeVisible();
    await expect(
      page.getByText(calendarName, { exact: true })
    ).not.toBeVisible();

    // 6. Delete the calendar
    page.once('dialog', dialog => dialog.accept());

    await Promise.all([
      page.waitForResponse(
        response =>
          response.url().includes('/api/calendars/') &&
          response.request().method() === 'DELETE' &&
          response.ok()
      ),
      page
        .getByRole('button', {
          name: new RegExp(`Delete calendar ${updatedName}`, 'i'),
        })
        .click(),
    ]);

    // Verify it's gone
    await expect(page.getByText(updatedName)).not.toBeVisible();
  });
});
