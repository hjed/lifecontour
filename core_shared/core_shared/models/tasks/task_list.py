"""The TaskList entity: a user's named home for tasks."""

from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum

from .exceptions import TaskListValidationError
from .task_icon import TaskIcon

# Mirrors the ``task_lists.name`` column bound.
MAX_TASK_LIST_NAME_LENGTH = 200


class TaskListArchiveFilter(StrEnum):
    """Which of a user's lists a listing returns, by archived state.

    ``ACTIVE`` and ``ALL`` come in the user's manual order; ``ARCHIVED`` comes
    most-recently-archived first, the order the archived lists page shows.
    """

    ACTIVE = "active"
    ARCHIVED = "archived"
    ALL = "all"


@dataclass(kw_only=True)
class TaskList:
    """A named list of tasks belonging to one user.

    A list has a name, an optional icon from the fixed set, a position among the
    user's lists, and an archived state. Only what the entity alone can know is
    validated here; whether the acting user owns the list, and whether it may be
    written while archived, are service-layer rules.

    Fields are keyword-only: later phases add the associated journal and the
    template columns, and positional construction would break silently then.

    Attributes:
        user_id: User who owns this list
        name: Display name (required, at most ``MAX_TASK_LIST_NAME_LENGTH``)
        icon: Optional icon from the fixed set
        position: Place among the owner's lists, 0 at the top. ``None`` until
            the repository places a new list (at the bottom) on insert, the
            same way ``id`` is ``None`` until then. Lists order by
            ``(position, id)``, so the order is total even if two share a
            position.
        archived_at: When the list was archived; ``None`` while it is not
        id: Unique identifier (auto-generated by database)
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    name: str
    icon: TaskIcon | None = None
    position: int | None = None
    archived_at: datetime | None = None
    id: int | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate list properties."""
        self._validate_user_id()
        self._validate_name()
        self._validate_icon()
        self._validate_position()

    @property
    def is_archived(self) -> bool:
        """Whether the list is archived (and so read-only until unarchived)."""
        return self.archived_at is not None

    def _validate_user_id(self) -> None:
        if not self.user_id or not self.user_id.strip():
            raise TaskListValidationError("user_id", "User ID is required")

    def _validate_name(self) -> None:
        if not self.name or not self.name.strip():
            raise TaskListValidationError("name", "List name is required")

        if len(self.name) > MAX_TASK_LIST_NAME_LENGTH:
            raise TaskListValidationError(
                "name",
                f"List name must be at most {MAX_TASK_LIST_NAME_LENGTH} characters",
            )

    def _validate_icon(self) -> None:
        """Accept only a ``TaskIcon``.

        A bare string is refused even when it spells a real key: the surfaces
        parse input into ``TaskIcon`` first, so a string reaching the entity
        means a caller skipped that step.
        """
        if self.icon is not None and not isinstance(self.icon, TaskIcon):
            raise TaskListValidationError(
                "icon",
                f"Icon must be a TaskIcon, got {self.icon!r}",
            )

    def _validate_position(self) -> None:
        if self.position is not None and self.position < 0:
            raise TaskListValidationError(
                "position", "Position must be zero or greater"
            )
