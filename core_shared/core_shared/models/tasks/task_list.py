"""The TaskList entity: a user's named home for tasks."""

from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum

from .exceptions import TaskListArchivedError, TaskListValidationError
from .task_icon import TaskIcon

# Mirrors the ``task_lists.name`` column bound.
MAX_TASK_LIST_NAME_LENGTH = 200


class TaskListArchiveFilter(StrEnum):
    """Which of a user's lists a listing returns, by archived state.

    ``ACTIVE`` and ``ALL`` come in the user's manual order; ``ARCHIVED`` comes
    most-recently-archived first, the order the archived lists page shows.
    """

    ACTIVE = "active"
    ARCHIVED = "archived"
    ALL = "all"


@dataclass(kw_only=True)
class TaskList:
    """A named list of tasks belonging to one user.

    A list has a name, an optional icon from the fixed set, a position among the
    user's lists, an optional associated journal, and an archived state. Only
    what the entity alone can know is
    validated here, plus the read-only rule of an archived list
    (:meth:`ensure_writable`); whether the acting user owns the list is a
    service-layer rule.

    Fields are keyword-only: later phases add the template columns, and
    positional construction would break silently then.

    Attributes:
        user_id: User who owns this list
        name: Display name (required, at most ``MAX_TASK_LIST_NAME_LENGTH``)
        icon: Optional icon from the fixed set
        position: Place among the owner's lists, 0 at the top. ``None`` until
            the repository places a new list (at the bottom) on insert, the
            same way ``id`` is ``None`` until then. Lists order by
            ``(position, id)``, so the order is total even if two share a
            position.
        archived_at: When the list was archived; ``None`` while it is not
        associated_journal_id: The one journal the list belongs to — a packing
            list for a trip — or ``None``. A journal may hold several lists.
            Whether the journal belongs to the list's owner is a service rule.
            An archived list keeps its association: it still shows, marked
            archived, on that journal's page.
        id: Unique identifier (auto-generated by database)
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    name: str
    icon: TaskIcon | None = None
    position: int | None = None
    archived_at: datetime | None = None
    associated_journal_id: int | None = None
    id: int | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate list properties."""
        self._validate_user_id()
        self._validate_name()
        self._validate_icon()
        self._validate_position()
        self._validate_associated_journal_id()

    @property
    def is_archived(self) -> bool:
        """Whether the list is archived (and so read-only until unarchived)."""
        return self.archived_at is not None

    def ensure_writable(self) -> None:
        """Refuse any write to an archived list, until it is unarchived.

        The one definition of "archived means read-only" that every list write
        consults — and that task writes on an archived list will consult too.
        Unarchiving is the only write it does not guard, being the way out.

        Raises:
            TaskListArchivedError: The list is archived.
        """
        if self.is_archived:
            # Only a persisted list can be archived through the service, so an
            # id is always there when this refuses.
            assert self.id is not None, "An archived list must be persisted"
            raise TaskListArchivedError(self.id)

    def _validate_user_id(self) -> None:
        if not self.user_id or not self.user_id.strip():
            raise TaskListValidationError("user_id", "User ID is required")

    def _validate_name(self) -> None:
        if not self.name or not self.name.strip():
            raise TaskListValidationError("name", "List name is required")

        if len(self.name) > MAX_TASK_LIST_NAME_LENGTH:
            raise TaskListValidationError(
                "name",
                f"List name must be at most {MAX_TASK_LIST_NAME_LENGTH} characters",
            )

    def _validate_icon(self) -> None:
        """Accept only a ``TaskIcon``.

        A bare string is refused even when it spells a real key: the surfaces
        parse input into ``TaskIcon`` first, so a string reaching the entity
        means a caller skipped that step.
        """
        if self.icon is not None and not isinstance(self.icon, TaskIcon):
            raise TaskListValidationError(
                "icon",
                f"Icon must be a TaskIcon, got {self.icon!r}",
            )

    def _validate_position(self) -> None:
        if self.position is not None and self.position < 0:
            raise TaskListValidationError(
                "position", "Position must be zero or greater"
            )

    def _validate_associated_journal_id(self) -> None:
        """An associated journal, when there is one, is a real journal id."""
        if self.associated_journal_id is not None and self.associated_journal_id <= 0:
            raise TaskListValidationError(
                "associated_journal_id", "Journal ID must be a positive integer"
            )


@dataclass(frozen=True, kw_only=True)
class TaskListSummary:
    """A list as the listing shows it: the list, and how many tasks are open.

    Attributes:
        task_list: The list itself
        open_task_count: Its not-done tasks; zero for a list with none
    """

    task_list: TaskList
    open_task_count: int


@dataclass(frozen=True, kw_only=True)
class TaskListDeletion:
    """What deleting a list did to its tasks.

    A list's tasks go with it, except those holding both a creating and a due
    journal: they stay as journal-only tasks. The ids are in ascending order,
    the order their rows were locked in.

    Attributes:
        task_list_id: The list that was deleted
        deleted_task_ids: Tasks deleted with the list, open and closed alike
        kept_task_ids: Tasks kept as journal-only, no longer on any list
    """

    task_list_id: int
    deleted_task_ids: tuple[int, ...]
    kept_task_ids: tuple[int, ...]
