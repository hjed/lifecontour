"""Domain entities for the tasks domain."""

from dataclasses import dataclass
from datetime import datetime

from .exceptions import TaskValidationError
from .task_status import TaskStatus


@dataclass
class Task:
    """Task aggregate root entity.

    A task is a short piece of plain text describing something the user needs to
    do, anchored to exactly two journals: the ``creating`` journal where the
    commitment arose, and the ``due`` journal — the future moment where it
    matters. The two may be the same journal.

    Only what the entity alone can know is validated here. Whether the due
    journal exists, belongs to the acting user, or is future-dated needs journal
    data and the user's timezone, so those invariants are enforced in the
    service layer where every entry point — REST and MCP alike — inherits them.

    Attributes:
        user_id: User who owns this task
        text: Plain-text description of the commitment (no length bound)
        creating_journal_id: Journal the commitment arose in; never changes
        due_journal_id: Journal the commitment is due in; may be retargeted
        status: One of not done (default), done, or cancelled
        id: Unique identifier (auto-generated by database)
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    text: str
    creating_journal_id: int
    due_journal_id: int
    status: TaskStatus = TaskStatus.NOT_DONE
    id: int | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate task properties."""
        self._validate_user_id()
        self._validate_text()
        self._validate_anchor("creating_journal_id", self.creating_journal_id)
        self._validate_anchor("due_journal_id", self.due_journal_id)
        self._validate_status()

    def _validate_user_id(self) -> None:
        """Validate user_id is not empty."""
        if not self.user_id or not self.user_id.strip():
            raise TaskValidationError("user_id", "User ID is required")

    def _validate_text(self) -> None:
        """Validate text is not empty.

        Task text is plain text with no length bound — anything richer than a
        short line belongs in a journal, but that is a product convention rather
        than a constraint the column enforces.
        """
        if not self.text or not self.text.strip():
            raise TaskValidationError("text", "Task text is required")

    def _validate_anchor(self, field: str, journal_id: int | None) -> None:
        """Validate a journal anchor is present.

        A task must have both a creating and a due journal, and can never exist
        with only one of them at any point in its life.
        """
        if journal_id is None:
            raise TaskValidationError(field, "A journal anchor is required")

        if journal_id <= 0:
            raise TaskValidationError(field, "Journal ID must be a positive integer")

    def _validate_status(self) -> None:
        """Validate status is one of the three domain values."""
        if not isinstance(self.status, TaskStatus):
            raise TaskValidationError(
                "status",
                f"Status must be a TaskStatus, got {self.status!r}",
            )
