"""Domain entities for the tasks domain."""

from dataclasses import dataclass
from datetime import date, datetime

from .exceptions import TaskAnchorMissingError, TaskJournalAnchor, TaskValidationError
from .task_icon import TaskIcon
from .task_recurrence import TASK_RECURRENCE_TYPES, TaskRecurrence
from .task_status import TaskStatus


@dataclass(kw_only=True)
class Task:
    """Task aggregate root entity.

    A task is a short piece of plain text describing something the user needs to
    do. It lives on a **list**, on a pair of **journals**, or on both (spec
    *Core invariants*):

    1. It has a list, a due journal, or both — never neither.
    2. With no list it is a **journal-only task** and keeps every earlier rule:
       a ``creating`` journal where the commitment arose and a ``due`` journal
       where it matters, both required. The two may be the same journal.
    3. It is on at most one list (one ``task_list_id``).
    4. It has a due date **or** a due journal, never both.
    5. A due date is only ever set on a task that is on a list.
    6. Only a task on a list recurs. (The spec narrows this to ordinary lists;
       list kinds do not exist yet.)

    These mirror the CHECKs of migrations ``0146`` and ``0150``, so a task that
    passes here is one the table accepts — except an unplaced list task's
    ``position``, which the insert assigns. Only what the entity alone can know is validated.
    Whether a journal or list exists and belongs to the acting user, whether a
    due journal is future-dated or a due date today or later, and whether a list
    is archived need other rows and the user's timezone, so they are enforced in
    the service layer, where every entry point — REST and MCP alike — inherits
    them.

    Fields are keyword-only, like ``TaskList``: each phase that adds a column
    adds a field, and positional construction would break silently then.

    Attributes:
        user_id: User who owns this task
        text: Plain-text description of the commitment (no length bound)
        creating_journal_id: Journal the commitment arose in; never changes.
            Required unless the task is on a list.
        due_journal_id: Journal the commitment is due in; may be retargeted.
            Required unless the task is on a list.
        task_list_id: The list the task lives on, if any
        position: Place on its list, 0 at the top. Only on a list task, and
            ``None`` until the repository places a new one (at the bottom) on
            insert, the same way ``TaskList.position`` and ``id`` are. A list's
            tasks order by ``(position, id)``.
        due_date: A calendar day in the user's timezone, with no time of day;
            list tasks only, never beside a due journal
        flagged: The single "this one matters" marker; any task may carry it
        icon: Optional icon from the fixed set; any task may carry it
        recurrence: How completing the task makes its next copy, if it
            recurs; list tasks only
        recurrence_of_task_id: The task this one was copied from when its
            predecessor recurred. A record of the past rather than a setting,
            so it is not limited to list tasks; never the task itself
        status: One of not done (default), done, or cancelled
        id: Unique identifier (auto-generated by database)
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    text: str
    creating_journal_id: int | None = None
    due_journal_id: int | None = None
    task_list_id: int | None = None
    position: int | None = None
    due_date: date | None = None
    flagged: bool = False
    icon: TaskIcon | None = None
    recurrence: TaskRecurrence | None = None
    recurrence_of_task_id: int | None = None
    status: TaskStatus = TaskStatus.NOT_DONE
    id: int | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate task properties."""
        self._validate_user_id()
        self._validate_text()
        self._validate_list()
        self._validate_anchor("creating_journal_id", self.creating_journal_id)
        self._validate_anchor("due_journal_id", self.due_journal_id)
        self._validate_position()
        self._validate_due_date()
        self._validate_flag()
        self._validate_icon()
        self._validate_recurrence()
        self._validate_recurrence_of()
        self._validate_status()

    def require_anchor(self, anchor: TaskJournalAnchor) -> int:
        """The id of one of the task's journal anchors, which must be present.

        For code whose existing contract still needs a journal: a journal-only
        task always has both, so on those paths a missing anchor is a broken
        invariant rather than a refusal (see :class:`TaskAnchorMissingError`).

        Raises:
            TaskAnchorMissingError: The task has no journal in that role.
        """
        journal_id = (
            self.creating_journal_id if anchor == "creating" else self.due_journal_id
        )
        if journal_id is None:
            raise TaskAnchorMissingError(self.id, anchor)
        return journal_id

    def _validate_user_id(self) -> None:
        """Validate user_id is not empty."""
        if not self.user_id or not self.user_id.strip():
            raise TaskValidationError("user_id", "User ID is required")

    def _validate_text(self) -> None:
        """Validate text is not empty.

        Task text is plain text with no length bound — anything richer than a
        short line belongs in a journal, but that is a product convention rather
        than a constraint the column enforces.
        """
        if not self.text or not self.text.strip():
            raise TaskValidationError("text", "Task text is required")

    def _validate_list(self) -> None:
        if self.task_list_id is not None and self.task_list_id <= 0:
            raise TaskValidationError(
                "task_list_id", "List ID must be a positive integer"
            )

    def _validate_anchor(self, field: str, journal_id: int | None) -> None:
        """Validate a journal anchor (invariants 1 and 2).

        A task with no list must have both a creating and a due journal, and can
        never exist with only one of them at any point in its life. A list task
        may have either, both or neither; an anchor it does have is still a real
        journal id.
        """
        if journal_id is None:
            if self.task_list_id is None:
                raise TaskValidationError(
                    field,
                    "A journal anchor is required",
                )
            return

        if journal_id <= 0:
            raise TaskValidationError(field, "Journal ID must be a positive integer")

    def _validate_position(self) -> None:
        if self.position is None:
            return
        if self.task_list_id is None:
            raise TaskValidationError(
                "position", "Only a task on a list has a position"
            )
        if self.position < 0:
            raise TaskValidationError("position", "Position must be zero or greater")

    def _validate_due_date(self) -> None:
        """Validate the due date's type and its invariants 4 and 5.

        ``datetime`` subclasses ``date``, so the type check refuses it by name:
        a due date is a calendar day with no time of day, and a ``datetime``
        here would mean a caller skipped converting into the user's timezone.
        """
        if self.due_date is None:
            return
        if isinstance(self.due_date, datetime) or not isinstance(self.due_date, date):
            raise TaskValidationError(
                "due_date",
                f"Due date must be a calendar date, got {self.due_date!r}",
            )
        if self.task_list_id is None:
            raise TaskValidationError(
                "due_date", "A due date can only be set on a task that is on a list"
            )
        if self.due_journal_id is not None:
            raise TaskValidationError(
                "due_date", "A task cannot have both a due date and a due journal"
            )

    def _validate_flag(self) -> None:
        if not isinstance(self.flagged, bool):
            raise TaskValidationError(
                "flagged", f"Flag must be true or false, got {self.flagged!r}"
            )

    def _validate_icon(self) -> None:
        """Accept only a ``TaskIcon``, as ``TaskList`` does.

        A bare string is refused even when it spells a real key: the surfaces
        parse input into ``TaskIcon`` first, so a string reaching the entity
        means a caller skipped that step.
        """
        if self.icon is not None and not isinstance(self.icon, TaskIcon):
            raise TaskValidationError(
                "icon", f"Icon must be a TaskIcon, got {self.icon!r}"
            )

    def _validate_recurrence(self) -> None:
        """Accept only a recurrence value object, and only on a list (invariant 6)."""
        if self.recurrence is None:
            return
        if not isinstance(self.recurrence, TASK_RECURRENCE_TYPES):
            raise TaskValidationError(
                "recurrence",
                f"Recurrence must be a TaskRecurrence, got {self.recurrence!r}",
            )
        if self.task_list_id is None:
            raise TaskValidationError("recurrence", "Only a task on a list can recur")

    def _validate_recurrence_of(self) -> None:
        if self.recurrence_of_task_id is None:
            return
        if self.recurrence_of_task_id <= 0:
            raise TaskValidationError(
                "recurrence_of_task_id", "Task ID must be a positive integer"
            )
        if self.recurrence_of_task_id == self.id:
            raise TaskValidationError(
                "recurrence_of_task_id", "A task cannot be a copy of itself"
            )

    def _validate_status(self) -> None:
        """Validate status is one of the three domain values."""
        if not isinstance(self.status, TaskStatus):
            raise TaskValidationError(
                "status",
                f"Status must be a TaskStatus, got {self.status!r}",
            )
