"""
Route entity for shared use across activity types.

Routes represent reusable track/route names that can be referenced by multiple
activity types (BUSHWALKING, CANYONING, CLIMBING, KAYAKING, CROSS_COUNTRY_SKIING, JOGGING).
"""

import xml.etree.ElementTree as ET
from dataclasses import dataclass
from datetime import datetime
from uuid import UUID


@dataclass
class Route:
    """
    Route entity representing a reusable route/track.

    Routes are user-specific and can be referenced by multiple journal entries
    of different activity types. They can optionally include GPX track data.

    Attributes:
        id: Unique identifier (UUID, auto-generated by database)
        user_id: User who owns this route (max 50 chars)
        name: Name of the route/track (required, max 200 chars)
        description: Optional description of the route
        gpx_data: Optional GPX track data in XML format
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    name: str
    id: UUID | None = None
    description: str | None = None
    gpx_data: str | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate route properties."""
        # Validate user_id
        if not self.user_id or not self.user_id.strip():
            raise ValueError("User ID is required")
        if len(self.user_id) > 50:
            raise ValueError("User ID cannot exceed 50 characters")

        # Validate name
        if not self.name or not self.name.strip():
            raise ValueError("Route name is required")
        if len(self.name) > 200:
            raise ValueError("Route name cannot exceed 200 characters")

        # Validate GPX data if provided
        if self.gpx_data is not None and self.gpx_data.strip():
            self._validate_gpx_data(self.gpx_data)

    def _validate_gpx_data(self, gpx_data: str) -> None:
        """
        Validate that GPX data is valid XML with a GPX root element.

        Args:
            gpx_data: GPX XML string to validate

        Raises:
            ValueError: If GPX data is not valid XML or missing GPX root element
        """
        try:
            root = ET.fromstring(gpx_data)
        except ET.ParseError as e:
            raise ValueError(f"GPX data must be valid XML: {e}") from e

        # Check for GPX root element (with or without namespace)
        if not (root.tag == "gpx" or root.tag.endswith("}gpx")):
            raise ValueError("GPX data must contain a <gpx> root element")
