"""ReviewItem domain entity for match candidate review queue.

Represents a potential match between a newly created journal and an existing one,
surfaced for user review rather than auto-merging.
"""

from dataclasses import dataclass
from datetime import datetime
from enum import StrEnum
from typing import Any

from .exceptions import JournalValidationError


class ReviewReason(StrEnum):
    """Reason why a review item was created."""

    EXTERNAL_LINK_MATCH = "external_link_match"  # Same external event already linked
    DUPLICATE_JOURNAL = "duplicate_journal"  # Similar title + overlapping dates
    NEEDS_REVIEW = "needs_review"  # General uncertain match


@dataclass
class ReviewItem:
    """
    Review item entity for the match candidate review queue.

    Created when a new journal is detected as a potential match for an existing
    journal. Users can review these to merge, link, or dismiss.

    Attributes:
        user_id: User who owns both journals
        source_journal_id: The newly created journal
        candidate_journal_id: The existing journal it may match
        reason: Why this match was flagged
        confidence_score: 0.0–1.0 match confidence from detection
        details: Extra info (e.g. which fields matched, similarity scores)
        id: Unique identifier (auto-generated by database)
        status: pending | resolved | dismissed
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    source_journal_id: int
    candidate_journal_id: int
    reason: ReviewReason
    confidence_score: float
    details: dict[str, Any] | None
    id: int | None = None
    status: str = "pending"
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate review item properties."""
        self._validate_user_id()
        self._validate_confidence_score()
        self._validate_journal_ids()

    def _validate_user_id(self) -> None:
        """Validate user_id is not empty."""
        if not self.user_id or not self.user_id.strip():
            raise JournalValidationError("user_id", "User ID is required")

    def _validate_confidence_score(self) -> None:
        """Validate confidence_score is between 0.0 and 1.0."""
        if self.confidence_score < 0.0 or self.confidence_score > 1.0:
            raise JournalValidationError(
                "confidence_score",
                "Confidence score must be between 0.0 and 1.0",
            )

    def _validate_journal_ids(self) -> None:
        """Validate source and candidate journal IDs are different."""
        if self.source_journal_id == self.candidate_journal_id:
            raise JournalValidationError(
                "source_journal_id",
                "source_journal_id and candidate_journal_id must be different",
            )
