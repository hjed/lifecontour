"""Domain entities for the journal domain."""

from dataclasses import dataclass
from datetime import datetime

from .constants import MAX_TITLE_LENGTH
from .exceptions import JournalValidationError
from .value_objects import EventDateRange


@dataclass
class Journal:
    """
    Journal aggregate root entity.

    Represents a journal entry with hierarchical support (parent-child relationships).
    Journals can have multiple types (handled in separate tables) and can be
    organized into a tree structure with maximum depth of 5 levels.

    Attributes:
        id: Unique identifier (auto-generated by database)
        user_id: User who owns this journal entry
        title: Title of the journal entry (max 500 chars)
        content: Markdown content of the journal entry
        event_date_range: Date range for the event (start and end timestamps)
        parent_id: ID of parent journal (for hierarchy), nullable
        order: Order among siblings (for manual ordering)
        created_at: Creation timestamp
        updated_at: Last update timestamp
    """

    user_id: str
    title: str
    content: str
    event_date_range: EventDateRange
    id: int | None = None
    parent_id: int | None = None
    order: int | None = None
    created_at: datetime | None = None
    updated_at: datetime | None = None

    def __post_init__(self) -> None:
        """Validate journal properties."""
        self._validate_user_id()
        self._validate_title()

    def _validate_user_id(self) -> None:
        """Validate user_id is not empty."""
        if not self.user_id or not self.user_id.strip():
            raise JournalValidationError("user_id", "User ID is required")

    def _validate_title(self) -> None:
        """Validate title is not empty and within length limit."""
        if not self.title or not self.title.strip():
            raise JournalValidationError("title", "Title is required")

        if len(self.title) > MAX_TITLE_LENGTH:
            raise JournalValidationError(
                "title", f"Title cannot exceed {MAX_TITLE_LENGTH} characters"
            )

    @property
    def is_child(self) -> bool:
        """Check if this journal has a parent (is a child journal)."""
        return self.parent_id is not None

    @property
    def is_root(self) -> bool:
        """Check if this journal is a root journal (no parent)."""
        return self.parent_id is None
